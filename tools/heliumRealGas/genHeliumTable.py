#!/usr/bin/env python3
"""Generate the helium real-gas property table read by the ltneRealGas library.

Source: CoolProp (MIT licence), helium EOS Ortiz-Vega et al., J. Phys. Chem. Ref. Data (2019); viscosity Arp
(NIST 1998); conductivity Hands (Cryogenics 1981), as selected by CoolProp. The same EOS is used by the NIST
Chemistry WebBook. Pin the version: pip install CoolProp==8.0.0

Usage: genHeliumTable.py <output file>
Grid: uniform in T and p (see TMIN... below); values at the nodes; the library interpolates bilinearly.
Fields, all per unit mass, SI:
  rho    density
  hDep   enthalpy departure from the ideal gas,  h(T,p) - h(T, p->0)
  cp, cv specific heats (total, real gas)
  sDep   entropy departure,  s(T,p) - [s(T,p->0) - R ln(p/p->0)]
  mu     dynamic viscosity
  kappa  thermal conductivity
The ideal-gas part is cp0 = 2.5 R (monatomic), with R from CoolProp's molar mass; the OpenFOAM case must use the
same value (hConst Cp) and molWeight, which this script prints.
"""
import sys
import numpy as np
import CoolProp
import CoolProp.CoolProp as CP

TMIN, TMAX, DT = 15.0, 95.0, 0.25          # K; CoolProp's viscosity has a jump near 100 K, so stop below it
PMIN, PMAX, DP = 0.5e6, 1.0e6, 0.025e6     # Pa
P_IDEAL = 1.0                              # Pa, the ideal-gas limit used for the departures
FLUID = 'Helium'

out = sys.argv[1]
Ts = np.round(np.arange(TMIN, TMAX + 1e-9, DT), 10)
ps = np.round(np.arange(PMIN, PMAX + 1e-3, DP), 6)
M = CP.PropsSI('M', FLUID)
R = CP.PropsSI('GAS_CONSTANT', FLUID) / M
W = 1e3 * M                                 # kg/kmol


def props(T, p):
    q = lambda k, TT, pp: CP.PropsSI(k, 'T', TT, 'P', pp, FLUID)
    h0, s0 = q('Hmass', T, P_IDEAL), q('Smass', T, P_IDEAL)
    return {
        'rho': q('Dmass', T, p),
        'hDep': q('Hmass', T, p) - h0,
        'cp': q('Cpmass', T, p),
        'cv': q('Cvmass', T, p),
        'sDep': q('Smass', T, p) - (s0 - R * np.log(p / P_IDEAL)),
        'mu': q('viscosity', T, p),
        'kappa': q('conductivity', T, p),
    }


FIELDS = ['rho', 'hDep', 'cp', 'cv', 'sDep', 'mu', 'kappa']
tab = {f: np.empty((len(Ts), len(ps))) for f in FIELDS}
for i, T in enumerate(Ts):
    for j, p in enumerate(ps):
        v = props(T, p)
        for f in FIELDS:
            tab[f][i, j] = v[f]

# bilinear interpolation error at every cell centre, against CoolProp
err = {f: (0.0, None) for f in ('rho', 'cp', 'mu', 'kappa')}
for i in range(len(Ts) - 1):
    for j in range(len(ps) - 1):
        Tm, pm = 0.5 * (Ts[i] + Ts[i + 1]), 0.5 * (ps[j] + ps[j + 1])
        ex = props(Tm, pm)
        for f in err:
            bil = 0.25 * (tab[f][i, j] + tab[f][i + 1, j] + tab[f][i, j + 1] + tab[f][i + 1, j + 1])
            e = abs(bil / ex[f] - 1)
            if e > err[f][0]:
                err[f] = (e, (Tm, pm))

with open(out, 'w') as fo:
    fo.write('/*--------------------------------*- C++ -*----------------------------------*\\\n')
    fo.write(f'  Helium real-gas property table for ltneRealGas, generated by tools/heliumRealGas/genHeliumTable.py\n')
    fo.write(f'  CoolProp {CoolProp.__version__} ({CoolProp.__gitrevision__}); EOS '
             f'{CP.get_fluid_param_string(FLUID, "BibTeX-EOS")}, viscosity '
             f'{CP.get_fluid_param_string(FLUID, "BibTeX-VISCOSITY")}, conductivity '
             f'{CP.get_fluid_param_string(FLUID, "BibTeX-CONDUCTIVITY")}\n')
    fo.write(f'  Ideal-gas part: molWeight {W:.9g} kg/kmol, R {R:.9g} J/kg/K, cp0 = 2.5 R = {2.5 * R:.9g} J/kg/K\n')
    fo.write('  Largest relative bilinear-interpolation error at cell centres (vs CoolProp):\n')
    for f, (e, at) in err.items():
        fo.write(f'    {f:6s} {e:.2e} at T = {at[0]:g} K, p = {at[1]:g} Pa\n')
    fo.write('  Layout: value(T_i, p_j) at index i*np + j, T_i = Tmin + i dT, p_j = pMin + j dp\n')
    fo.write('\\*---------------------------------------------------------------------------*/\n\n')
    fo.write(f'Tmin {TMIN:g};\ndT {DT:g};\nnT {len(Ts)};\npMin {PMIN:g};\ndp {DP:g};\nnp {len(ps)};\n')
    fo.write(f'molWeight {W:.9g};\ncp0 {2.5 * R:.9g};\n\n')
    for f in FIELDS:
        fo.write(f'{f}\n{len(Ts) * len(ps)}\n(\n')
        flat = tab[f].reshape(-1)
        for k in range(0, len(flat), 6):
            fo.write(' '.join(f'{x:.9e}' for x in flat[k:k + 6]) + '\n')
        fo.write(');\n\n')
print(f'{out}: nT {len(Ts)} np {len(ps)}; molWeight {W:.9g}, cp0 {2.5 * R:.9g}')
for f, (e, at) in err.items():
    print(f'  bilinear error {f}: {e:.2e} at {at}')
